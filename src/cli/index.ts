import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { createJiti } from 'jiti';
import { type FlowApp, toMermaid } from 'react-flow-app';
import { check, type GraphSnapshot } from 'react-flow-app/testing';

const HELP = `react-flow-app check — validates the flows, keeps the graph snapshot and diagram in the repo,
and compares them with a base branch.

Usage
  react-flow-app check [options]

Options
  --app <file>        File that exports the app (default: src/app.flow.ts)
  --export <name>     Export name (default: the first export created with createFlowApp)
  --snapshot <file>   Graph snapshot kept in the repo (default: flows.graph.json)
  --diagram <file>    Mermaid diagram kept in the repo (default: FLOWS.md)
  --write             Update the snapshot and the diagram
  --base <ref>        Compare with the snapshot of a git ref (e.g. origin/main) and print a summary
  --report <file>     Write that summary to a file (e.g. for a CI comment) instead of printing it
  --strict            Warnings fail too (e.g. a branch without samples)
  -h, --help          Show this help

Exit code 1 when there are errors, warnings with --strict, or a stale snapshot.`;

const isApp = (value: unknown): value is FlowApp =>
	typeof value === 'object' && value !== null && (value as { kind?: unknown }).kind === 'app';

/** Removes line and block comments outside strings, and trailing commas (tsconfig is JSONC). */
function stripJsonc(text: string): string {
	let out = '';
	for (let i = 0; i < text.length; i++) {
		const char = text[i];
		if (char === '"') {
			let end = i + 1;
			while (end < text.length && text[end] !== '"') end += text[end] === '\\' ? 2 : 1;
			out += text.slice(i, end + 1);
			i = end;
		} else if (char === '/' && text[i + 1] === '/') {
			while (i < text.length && text[i] !== '\n') i++;
			out += '\n';
		} else if (char === '/' && text[i + 1] === '*') {
			i = text.indexOf('*/', i + 2) + 1 || text.length;
		} else {
			out += char;
		}
	}
	return out.replace(/,(\s*[}\]])/g, '$1');
}

/**
 * `compilerOptions.paths` of the project's tsconfig, as jiti aliases. Exact entries (`@app/flows`) and
 * prefix entries (`@/<wildcard>` → `src/<wildcard>`) are supported; other wildcard patterns are skipped.
 */
export function aliasesFrom(cwd: string): Record<string, string> {
	const file = resolve(cwd, 'tsconfig.json');
	if (!existsSync(file)) return {};
	try {
		const { compilerOptions = {} } = JSON.parse(stripJsonc(readFileSync(file, 'utf8'))) as {
			compilerOptions?: { baseUrl?: string; paths?: Record<string, string[]> };
		};
		const base = resolve(cwd, compilerOptions.baseUrl ?? '.');
		const aliases: Record<string, string> = {};
		for (const [from, [to] = []] of Object.entries(compilerOptions.paths ?? {})) {
			if (!to) continue;
			if (!from.includes('*') && !to.includes('*')) aliases[from] = resolve(base, to);
			else if (from.endsWith('/*') && to.endsWith('/*') && !from.slice(0, -2).includes('*') && !to.slice(0, -2).includes('*')) {
				aliases[from.slice(0, -2)] = resolve(base, to.slice(0, -2));
			}
		}
		return aliases;
	} catch {
		return {};
	}
}

async function loadApp(cwd: string, file: string, exportName?: string): Promise<FlowApp> {
	const path = resolve(cwd, file);
	if (!existsSync(path)) throw new Error(`App file not found: ${file} (use --app)`);
	const jiti = createJiti(path, { jsx: true, alias: aliasesFrom(cwd), interopDefault: true });
	const module = (await jiti.import(path)) as Record<string, unknown>;
	const app = exportName ? module[exportName] : Object.values(module).find(isApp);
	if (!isApp(app)) {
		throw new Error(
			exportName ? `"${exportName}" in ${file} is not a flow app` : `No export of ${file} was created with createFlowApp`
		);
	}
	return app;
}

function readBase(cwd: string, snapshotFile: string, ref: string): GraphSnapshot {
	const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd, encoding: 'utf8' }).trim();
	const path = relative(root, snapshotFile).split('\\').join('/');
	try {
		return JSON.parse(execFileSync('git', ['show', `${ref}:${path}`], { cwd, encoding: 'utf8', stdio: 'pipe' })) as GraphSnapshot;
	} catch {
		// No snapshot on the base yet: everything shows up as new.
		return { version: 1, nodes: [], edges: [] };
	}
}

function diagramMarkdown(app: FlowApp, graph: ReturnType<typeof check>['graph']): string {
	return [
		'<!-- Generated by `react-flow-app check --write`. Do not edit by hand. -->',
		'',
		'# Flows',
		'',
		`${app.flows.length} flows, ${graph.nodes.length} steps, ${graph.edges.length} transitions.`,
		'`((step))` initial · `{{@overlay}}` overlay · `-.->` between flows · `↩` goto.exit() · `⟲` resumes the flow · `⚙` effect',
		'',
		'```mermaid',
		toMermaid(graph),
		'```',
		'',
	].join('\n');
}

export async function main(argv: string[], cwd = process.cwd()): Promise<number> {
	const { values, positionals } = parseArgs({
		args: argv,
		allowPositionals: true,
		options: {
			app: { type: 'string', default: 'src/app.flow.ts' },
			export: { type: 'string' },
			snapshot: { type: 'string', default: 'flows.graph.json' },
			diagram: { type: 'string', default: 'FLOWS.md' },
			write: { type: 'boolean', default: false },
			base: { type: 'string' },
			report: { type: 'string' },
			strict: { type: 'boolean', default: false },
			help: { type: 'boolean', short: 'h', default: false },
		},
	});

	if (values.help || positionals[0] !== 'check') {
		console.log(HELP);
		return values.help ? 0 : 1;
	}

	const app = await loadApp(cwd, values.app, values.export);
	const snapshotFile = resolve(cwd, values.snapshot);
	const diagramFile = resolve(cwd, values.diagram);
	const committed = existsSync(snapshotFile) ? (JSON.parse(readFileSync(snapshotFile, 'utf8')) as GraphSnapshot) : undefined;
	const base = values.base ? readBase(dirname(snapshotFile), snapshotFile, values.base) : undefined;
	const result = check(app, { committed: values.write ? undefined : committed, base, strict: values.strict });

	for (const issue of result.issues) {
		console.log(`${issue.severity === 'error' ? '✘' : '⚠'} ${issue.where}: ${issue.message} [${issue.code}]`);
	}
	const errors = result.issues.filter(issue => issue.severity === 'error').length;
	console.log(
		`${result.graph.nodes.length} steps, ${result.graph.edges.length} transitions, ${errors} error(s), ${result.issues.length - errors} warning(s)`
	);

	if (values.write) {
		writeFileSync(snapshotFile, `${JSON.stringify(result.snapshot, null, '\t')}\n`);
		writeFileSync(diagramFile, diagramMarkdown(app, result.graph));
		console.log(`Updated ${relative(cwd, snapshotFile)} and ${relative(cwd, diagramFile)}`);
	} else if (result.stale) {
		console.log(`✘ ${relative(cwd, snapshotFile)} is out of date: run \`react-flow-app check --write\` and commit it.`);
	} else if (!committed) {
		console.log(`No snapshot yet: run \`react-flow-app check --write\` to create ${relative(cwd, snapshotFile)}.`);
	}

	if (result.report) {
		if (values.report) writeFileSync(resolve(cwd, values.report), `${result.report}\n`);
		else console.log(`\n${result.report}`);
	}

	return result.ok ? 0 : 1;
}
